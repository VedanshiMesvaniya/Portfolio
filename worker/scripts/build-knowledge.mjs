/* Reads every PDF / .txt / .md in /knowledge (and /knowledge/private), splits the text into
 * small chunks, and writes:
 *   worker/src/knowledge.generated.js          public chunks, bundled into the worker
 *   worker/src/knowledge.private.generated.js  private chunks, bundled into the worker (git-ignored)
 *   assets/data/knowledge.json                 public chunks, used by the site's built-in answers
 * Run:  npm run build:knowledge
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const KNOWLEDGE = path.join(root, 'knowledge');
const PRIVATE = path.join(KNOWLEDGE, 'private');
const OUT_PUBLIC = path.join(root, 'worker/src/knowledge.generated.js');
const OUT_PRIVATE = path.join(root, 'worker/src/knowledge.private.generated.js');
const OUT_SITE = path.join(root, 'assets/data/knowledge.json');

const CHUNK_CHARS = 850;
const EXTENSIONS = new Set(['.pdf', '.txt', '.md']);

const titleOf = (file) => path.basename(file, path.extname(file)).replace(/[_-]+/g, ' ').replace(/\s+/g, ' ').trim();

async function listFiles(dir) {
  let entries = [];
  try { entries = await fs.readdir(dir, { withFileTypes: true }); } catch { return []; }
  return entries
    .filter((e) => e.isFile() && !e.name.startsWith('_') && !e.name.startsWith('.') && EXTENSIONS.has(path.extname(e.name).toLowerCase()))
    .map((e) => path.join(dir, e.name))
    .sort();
}

/* ---- PDF text, rebuilt line by line in reading order ---- */
let pdfjs;
async function pdfPages(file) {
  pdfjs ||= await import('pdfjs-dist/legacy/build/pdf.mjs');
  const data = new Uint8Array(await fs.readFile(file));
  const pdf = await pdfjs.getDocument({ data, useSystemFonts: true, isEvalSupported: false, verbosity: 0 }).promise;
  const pages = [];
  for (let n = 1; n <= pdf.numPages; n++) {
    const page = await pdf.getPage(n);
    const content = await page.getTextContent();
    const items = content.items
      .filter((i) => typeof i.str === 'string' && i.str.trim() !== '')
      .map((i) => ({ s: i.str, x: i.transform[4], y: i.transform[5], w: i.width || 0 }));
    items.sort((a, b) => (Math.abs(b.y - a.y) > 3 ? b.y - a.y : a.x - b.x));
    const lines = [];
    let cur = null;
    for (const it of items) {
      if (cur && Math.abs(cur.y - it.y) <= 3) {
        const gap = it.x - cur.endX;
        cur.text += (gap > 1.5 ? ' ' : '') + it.s;
        cur.endX = it.x + it.w;
      } else {
        cur = { y: it.y, text: it.s, endX: it.x + it.w };
        lines.push(cur);
      }
    }
    pages.push(lines.map((l) => l.text.replace(/\s+/g, ' ').trim()).filter(Boolean));
  }
  return pages;
}

async function textPages(file) {
  const raw = await fs.readFile(file, 'utf8');
  return [raw.split(/\r?\n/).map((l) => l.replace(/\s+/g, ' ').trim()).filter(Boolean)];
}

function chunkLines(lines) {
  const out = [];
  let buf = [];
  let size = 0;
  for (const line of lines) {
    if (size + line.length > CHUNK_CHARS && buf.length) {
      out.push(buf.join('\n'));
      buf = buf.slice(-2);                       // two lines of overlap keep context across chunks
      size = buf.join('\n').length;
    }
    buf.push(line);
    size += line.length + 1;
  }
  if (buf.length) out.push(buf.join('\n'));
  return out.filter((t) => t.length >= 30);
}

async function readAll(dir, label) {
  const chunks = [];
  const files = await listFiles(dir);
  for (const file of files) {
    const ext = path.extname(file).toLowerCase();
    let pages;
    try { pages = ext === '.pdf' ? await pdfPages(file) : await textPages(file); }
    catch (err) { console.warn(`  ! could not read ${path.basename(file)}: ${err.message}`); continue; }
    let count = 0;
    pages.forEach((lines, i) => {
      chunkLines(lines).forEach((text) => {
        count++;
        chunks.push({ id: `${path.basename(file)}#${chunks.length + 1}`, file: path.basename(file), title: titleOf(file), page: i + 1, text });
      });
    });
    console.log(`  ${label.padEnd(7)} ${path.basename(file)}: ${count} chunks`);
    if (!count) console.warn(`  ! no text found in ${path.basename(file)} (scanned PDFs need OCR first)`);
  }
  return chunks;
}

const stamp = new Date().toISOString();
console.log('Building knowledge from', path.relative(root, KNOWLEDGE) + '/');
const publicChunks = await readAll(KNOWLEDGE, 'public');
const privateChunks = await readAll(PRIVATE, 'private');

const banner = '// Generated by worker/scripts/build-knowledge.mjs. Do not edit by hand.\n';
await fs.writeFile(OUT_PUBLIC, `${banner}export default ${JSON.stringify({ generatedAt: stamp, chunks: publicChunks }, null, 1)};\n`);
await fs.writeFile(OUT_PRIVATE, `${banner}export default ${JSON.stringify({ generatedAt: stamp, chunks: privateChunks }, null, 1)};\n`);
await fs.mkdir(path.dirname(OUT_SITE), { recursive: true });
await fs.writeFile(OUT_SITE, JSON.stringify({ generatedAt: stamp, chunks: publicChunks.map(({ file, title, page, text }) => ({ file, title, page, text })) }, null, 1) + '\n');
console.log(`Done: ${publicChunks.length} public and ${privateChunks.length} private chunks.`);
